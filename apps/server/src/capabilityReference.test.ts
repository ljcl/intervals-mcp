/**
 * docs/Intervals_MCP_Server.md is generated from the skills (#528).
 *
 * The skills in apps/server/skills/ are the one home of the long-form guide.
 * A client that supports skills over MCP loads them from the server. A client
 * without them gets the same text as one file, which the athlete uploads as
 * project knowledge. This test renders that file from the skills and fails
 * when the committed copy differs, so the two cannot drift. After a skill
 * changes, regenerate it:
 *
 *     UPDATE_CAPABILITY_REFERENCE=1 bunx vitest run src/capabilityReference.test.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { buildSkillCatalog, SKILLS_DIR, type SkillCatalog } from "./skills";

const DOC_URL = new URL(
  "../../../docs/Intervals_MCP_Server.md",
  import.meta.url,
);

/** The skills in the order the document gives them: basics first. */
const SKILL_ORDER = [
  "reading-intervals-data",
  "run-analysis",
  "fitness-and-racing",
  "route-planning",
  "activity-writes",
];

const HEADER = `# Intervals MCP Server: capability reference

<!-- Generated from apps/server/skills/ by apps/server/src/capabilityReference.test.ts. Do not edit this file: edit the skills, then run UPDATE_CAPABILITY_REFERENCE=1 bunx vitest run src/capabilityReference.test.ts in apps/server. -->

This file is the server's skills in one document: what each tool answers,
the usual sequence of calls, and the rules for reading the numbers and for
the writes.

- A client that supports skills over MCP (Claude and Claude Code) loads
  these skills from the server when a task needs them. It needs nothing from
  this file.
- For a client without skills, upload this file as project knowledge in a
  Claude project that is connected to the server.

The server also sends a short version to every chat as its MCP
instructions: the routing, the id format, units and time zone, and the rules
for the write tools. The full per-tool schemas are in [tools.md](tools.md).
`;

/** The text after the YAML frontmatter. */
function body(markdown: string): string {
  const match = /^---\n[\s\S]*?\n---\n/.exec(markdown);
  return (match ? markdown.slice(match[0].length) : markdown).trim();
}

/**
 * Moves every heading `levels` deeper, outside code fences, and turns a link
 * to a skill's own reference file into its title, because the reference
 * follows in this document.
 */
function nest(markdown: string, levels: number): string {
  let fenced = false;
  return markdown
    .split("\n")
    .map((line) => {
      if (/^(```|~~~)/.test(line)) fenced = !fenced;
      if (fenced) return line;
      const heading = /^(#+) /.exec(line);
      const nested = heading
        ? `${"#".repeat(heading[1]!.length + levels)}${line.slice(heading[1]!.length)}`
        : line;
      return nested.replace(
        /\[([^\]]+)\]\(references\/[^)]+\.md\)/g,
        "$1 (below)",
      );
    })
    .join("\n");
}

function title(markdown: string, fallback: string): string {
  return /^# (.+)$/m.exec(markdown)?.[1] ?? fallback;
}

function renderCapabilityReference(catalog: SkillCatalog): string {
  const sections: string[] = [HEADER.trim()];
  const contents: string[] = [];
  const parts: string[] = [];
  for (const name of SKILL_ORDER) {
    const skill = catalog.skills.find((s) => s.frontmatter.name === name);
    if (!skill) throw new Error(`no skill named ${name}`);
    const skillMd = catalog.files.get(skill.uri)!.text;
    const skillBody = body(skillMd);
    contents.push(
      `- **${title(skillBody, name)}** (skill \`${name}\`): ${skill.frontmatter.description}`,
    );
    const refs = (skill.resources === "dynamic" ? [] : skill.resources)
      .map((r) => r.uri)
      .filter((uri) => uri !== skill.uri)
      .map((uri) => nest(catalog.files.get(uri)!.text.trim(), 2));
    parts.push([nest(skillBody, 1), ...refs].join("\n\n"));
  }
  sections.push(`## Contents\n\n${contents.join("\n")}`);
  sections.push(...parts);
  return `${sections.join("\n\n").trimEnd()}\n`;
}

describe("docs/Intervals_MCP_Server.md", () => {
  it("places every shipped skill in the document", async () => {
    const catalog = await buildSkillCatalog(SKILLS_DIR);

    expect(catalog.skills.map((s) => s.frontmatter.name).sort()).toEqual(
      [...SKILL_ORDER].sort(),
    );
  });

  it("is the skills rendered as one file", async () => {
    const rendered = renderCapabilityReference(
      await buildSkillCatalog(SKILLS_DIR),
    );
    if (process.env.UPDATE_CAPABILITY_REFERENCE === "1") {
      writeFileSync(DOC_URL, rendered);
    }

    expect(
      readFileSync(DOC_URL, "utf8"),
      "docs/Intervals_MCP_Server.md is out of date: run UPDATE_CAPABILITY_REFERENCE=1 bunx vitest run src/capabilityReference.test.ts in apps/server",
    ).toBe(rendered);
  });
});
