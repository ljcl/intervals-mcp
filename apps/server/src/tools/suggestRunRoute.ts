const name = "suggest-run-route";

const description = `
Suggests where to run a planned run from the intervals.icu calendar: the
athlete's past runs from that start that fit the distance and terrain,
plus a new route generated by OpenRouteService, or three new routes where
the athlete has no history (travel), for "where should I run tomorrow?"
or "plan routes for this week's runs". To show the routes on a
map, use view-route-suggestions instead; its result has this text too.

Pass what the planned run says: start and end as a place with its city
("Embarcadero, San Francisco") or "lat,lng", via as an ordered list of them;
terrain flat for intervals or fartlek, hill-repeats for hill sprints,
rolling or hilly when the plan says so. The result starts each run with
its calendar description: if that names a place or terrain you did not
pass, call again with it. A planned run's stored distance can disagree
with its name; when it does, pass distanceKm.

Notes:
- Without start: HOME_START, else the most frequent start of recent GPS
  runs.
- Without ORS_API_KEY: past runs and stitched routes only, and no place
  lookup (pass lat,lng).
- Start, end and via points are sent to OpenRouteService, and the area's
  bounding box to OpenStreetMap Overpass, which counts road crossings.
- Fewer crossings rank first when Overpass answers (often not); else new
  routes rank by share on paths.
- A new route usually lands within 5% of the distance; a loop over 25% off
  is dropped, a via route keeps its nearest with a warning. The gap is shown.
- With via: past runs passing every via in order (any distance or
  terrain), then a route stitched from sections of past runs between the
  vias. A via matching only a suburb or city is refused.
- A week of runs shares one budget of routing calls; later runs may get
  past runs only, with a warning.
`;

const placeText = z.string().trim().min(2).max(120);
const placeInput = (text: string) => placeText.optional().describe(text);
/** Via points one call may name; each is looked up and routed through. */
const MAX_VIA = 5;
const viaList = z.array(placeText).min(1).max(MAX_VIA);

/** A host still holding the string-only `via` schema sends a list as its JSON text. */
function viaFromText(text: string): unknown {
  if (!text.startsWith("[")) return [text];
  try {
    return JSON.parse(text);
  } catch {
    return [text];
  }
}

const inputSchema = z.object({
  date: dateInputSchema
    .optional()
    .describe("First day to look for a planned run, YYYY-MM-DD; default today"),
  days: z
    .number()
    .int()
    .min(1)
    .max(7)
    .default(1)
    .describe(
      "1 for the first planned run on or after date; up to 7 for every planned run in that many days, with different routes for each",
    ),
  distanceKm: z
    .number()
    .positive()
    .max(100)
    .optional()
    .describe(
      "Distance to plan for in km, overriding the planned run's stored distance (every run in the window); needed when no run is planned",
    ),
  start: placeInput(
    "Where the run starts: a place with its city, or lat,lng; default the athlete's usual start",
  ),
  end: placeInput(
    "Where a point-to-point run ends: a place with its city, or lat,lng",
  ),
  via: z
    .union([placeText.transform(viaFromText).pipe(viaList), viaList])
    .optional()
    .describe(
      "A place the route must pass, or a list passed in that order: each a place with its city, or lat,lng",
    ),
  shape: z
    .enum(["loop", "out-and-back", "point-to-point"])
    .optional()
    .describe("Default loop, or point-to-point when end is given"),
  terrain: z
    .enum(["any", "flat", "rolling", "hilly", "hill-repeats"])
    .default("any")
    .describe(
      "flat for intervals or fartlek; hill-repeats finds a 60-200 m stretch at 5-12%; rolling or hilly as planned",
    ),
});

type SuggestRunRouteInput = z.infer<typeof inputSchema>;

const START_SOURCE = {
  argument: "given",
  env: "HOME_START",
  inferred: "inferred from recent runs",
} as const;

function km(meters: number): string {
  return (meters / 1000).toFixed(1);
}

function signedKm(meters: number): string {
  return `${meters >= 0 ? "+" : "-"}${km(Math.abs(meters))}`;
}

/** About 100 m: enough to place a start, not a front door. */
const round3 = (value: number) => Math.round(value * 1e3) / 1e3;

const place = (p: Place) => ({
  label: p.label,
  lat: round3(p.point[0]),
  lng: round3(p.point[1]),
});

/**
 * Stores every candidate that is not a past run so stitch-route, view-route-map and
 * export-route can use it by route_id. A store that cannot write (a
 * read-only volume) leaves the id out rather than failing the suggestion.
 */
export async function storeGeneratedCandidates(
  s: RouteSuggestions,
): Promise<Map<RouteCandidate, string>> {
  const ids = new Map<RouteCandidate, string>();
  for (const run of s.runs) {
    for (const c of run.candidates) {
      if (c.kind === "past") continue;
      try {
        ids.set(
          c,
          await storeSuggestedRoute({
            name: `${run.name} ${run.date}: ${c.name}`,
            track: c.track,
            climb_m: c.climb_m,
            path_share: c.path_share,
            shape: c.shape,
          }),
        );
      } catch {
        // The suggestion stands without an id.
      }
    }
  }
  return ids;
}

/** The tool's structured result: no geometry (the app gets that). */
export function toStructured(
  s: RouteSuggestions,
  routeIds: ReadonlyMap<RouteCandidate, string> = new Map(),
) {
  return {
    count: s.runs.length,
    generation_available: s.generation_available,
    runs: s.runs.map((run) => ({
      event_id: run.event_id,
      date: run.date,
      name: run.name,
      description: run.description,
      distance_m: Math.round(run.distance_m),
      distance_source: run.distance_source,
      start: {
        label: run.start.label,
        lat: round3(run.start.point[0]),
        lng: round3(run.start.point[1]),
        source: run.start.source,
        history_runs: run.start.history_runs,
      },
      end: run.end ? place(run.end) : null,
      // The first via point, as before via took a list; via_points has them all.
      via: run.via[0] ? place(run.via[0]) : null,
      via_points: run.via.map(place),
      shape: run.shape,
      terrain: run.terrain,
      candidates: run.candidates.map((c) => ({
        // Stitched goes out as generated: a new kind breaks hosts holding the old tool list (outputSchemaCompat.test.ts).
        kind: c.kind === "past" ? ("past" as const) : ("generated" as const),
        activity_id: c.activity_id,
        name: c.name,
        date: c.date,
        shape: c.shape,
        route_id: routeIds.get(c) ?? null,
        distance_m: Math.round(c.distance_m),
        distance_diff_m: Math.round(c.distance_m - run.distance_m),
        climb_m: Math.round(c.climb_m),
        climb_per_km: Math.round(climbPerKm(c.climb_m, c.distance_m) * 10) / 10,
        path_share:
          c.path_share === null ? null : Math.round(c.path_share * 100) / 100,
        history_share:
          c.history_share === undefined
            ? null
            : Math.round(c.history_share * 100) / 100,
        crossings_per_km: c.crossings_per_km,
        hill: c.hill,
        summary: c.summary,
      })),
      warnings: run.warnings,
    })),
    warnings: s.warnings,
  };
}

function lines(structured: ReturnType<typeof toStructured>): string[] {
  const out: string[] = [];
  for (const run of structured.runs) {
    const source =
      run.distance_source === "event" ? "from the event" : "as asked";
    out.push(`${run.date}: ${run.name} (${km(run.distance_m)} km, ${source})`);
    if (run.description)
      out.push(`  Plan: ${run.description.replace(/\s+/g, " ").slice(0, 300)}`);
    out.push(`Start: ${run.start.label} (${START_SOURCE[run.start.source]})`);
    if (run.end) out.push(`End: ${run.end.label}`);
    if (run.via_points.length > 0)
      out.push(`Via: ${run.via_points.map((p) => p.label).join(", then ")}`);
    run.candidates.forEach((c, i) => {
      const head =
        c.kind === "past"
          ? `Past run ${c.date} (${c.activity_id})`
          : c.route_id
            ? `${c.name} (route ${c.route_id})`
            : c.name;
      const crossings =
        c.crossings_per_km === null
          ? ""
          : `, ${c.crossings_per_km} crossings/km`;
      const paths =
        c.path_share === null
          ? ""
          : `, ${Math.round(c.path_share * 100)}% on paths`;
      const own =
        c.history_share === null
          ? ""
          : `, ${Math.round(c.history_share * 100)}% from your runs`;
      const tail =
        c.kind === "past"
          ? `, ${c.shape}. ${c.summary}`
          : `${paths}${own}, ${c.summary}`;
      out.push(
        `${i + 1}. ${head}: ${km(c.distance_m)} km (${signedKm(c.distance_diff_m)} km), ${c.climb_m} m climb${crossings}${tail}`,
      );
      if (c.hill)
        out.push(
          `   Hill for repeats: ${c.hill.length_m} m at ${c.hill.grade_pct}%, from ${km(c.hill.start_m)} km`,
        );
    });
    if (run.candidates.length === 0) out.push("No candidate routes.");
    for (const warning of run.warnings) out.push(`Warning: ${warning}`);
    out.push("");
  }
  for (const warning of structured.warnings) out.push(`Warning: ${warning}`);
  if (!structured.generation_available)
    out.push("New routes need ORS_API_KEY; only past runs were offered.");
  return out;
}

/** Config the engine needs, read once per call. */
export function routeSuggestionEnv(): SuggestionEnv {
  return {
    orsKey: getOrsApiKey(),
    homeStart: getHomeStart(),
    today: todayLocal(getTimeZone()),
  };
}

export const suggestRunRouteTool = {
  name,
  title: "Route suggestions",
  description,
  inputSchema,
  annotations: READ_ONLY,
  outputSchema: RouteSuggestionsOutputSchema,
  execute: async (
    args: SuggestRunRouteInput,
    apiKey: string,
    progress: ReportProgress = NO_PROGRESS,
  ) => {
    try {
      const suggestions = await loadRouteSuggestions(
        apiKey,
        args,
        routeSuggestionEnv(),
        progress,
      );
      const structured = toStructured(
        suggestions,
        await storeGeneratedCandidates(suggestions),
      );
      warnOnSchemaDrift(name, RouteSuggestionsOutputSchema, structured);
      return {
        content: [
          { type: "text" as const, text: lines(structured).join("\n").trim() },
        ],
        structuredContent: structured,
      };
    } catch (error) {
      if (error instanceof RouteSuggestionError) {
        noteToolFailure(error);
        return {
          content: [{ type: "text" as const, text: `❌ ${error.message}` }],
          isError: true,
        };
      }
      return {
        content: [
          {
            type: "text" as const,
            text: toolErrorText(error, { context: "suggest a run route" }),
          },
        ],
        isError: true,
      };
    }
  },
};
